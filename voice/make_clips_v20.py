import subprocess, struct, os

SR = 44100
WORDS = ["forty", "thirtyfive", "thirty", "twentyfive", "twenty", "nineteen", "eighteen", "seventeen", "sixteen",
         "fifteen", "fourteen", "thirteen", "twelve", "eleven",
         "ten", "nine", "eight", "seven", "six", "five", "four",
         "three", "two", "one"]
BASE = os.path.expanduser("~/workspace/height-caller/voice")

def load_samples(mp3):
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", mp3, "-f", "s16le", "-ac", "1", "-ar", str(SR), "-"],
        capture_output=True, check=True).stdout
    n = len(raw) // 2
    return list(struct.unpack("<%dh" % n, raw))

def trim(s, thresh_ratio=0.03, pad_ms=30):
    peak = max(abs(x) for x in s) or 1
    th = peak * thresh_ratio
    first = next(i for i, x in enumerate(s) if abs(x) > th)
    last = len(s) - next(i for i, x in enumerate(reversed(s)) if abs(x) > th)
    pad = int(SR * pad_ms / 1000)
    return s[max(0, first - pad): min(len(s), last + pad)], peak

def process(s):
    s, peak = trim(s)
    gain = 29000.0 / peak
    out = [int(max(-32767, min(32767, x * gain))) for x in s]
    fade = int(SR * 0.005)
    for i in range(min(fade, len(out))):
        f = i / fade
        out[i] = int(out[i] * f)
        out[-1 - i] = int(out[-1 - i] * f)
    return out

lines = []
lines.append("// voice_clips.h - spoken callout numbers for the height caller.")
lines.append("// Synthesized speech, 44100 Hz mono 16-bit PCM, peak-normalized.")
lines.append("// Generated by make_clips_v20.py - do not edit by hand.")
lines.append("#pragma once")
lines.append("")
total = 0
for w in WORDS:
    samples = process(load_samples(os.path.join(BASE, w + ".mp3")))
    total += len(samples)
    name = "CLIP_" + w.upper()
    lines.append("static const int16_t %s[] PROGMEM = {" % name)
    for i in range(0, len(samples), 12):
        chunk = ", ".join(str(x) for x in samples[i:i + 12])
        lines.append("  " + chunk + ("," if i + 12 < len(samples) else ""))
    lines.append("};")
    lines.append("#define %s_LEN %d" % (name, len(samples)))
    lines.append("")
    print("%s: %d samples, %.2f s" % (w, len(samples), len(samples) / SR))
print("TOTAL: %d samples = %d bytes of flash" % (total, total * 2))
out_path = os.path.expanduser("~/workspace/height-caller/arduino/height_caller_v20/voice_clips.h")
os.makedirs(os.path.dirname(out_path), exist_ok=True)
with open(out_path, "w") as f:
    f.write("\n".join(lines))
print("wrote", out_path)
